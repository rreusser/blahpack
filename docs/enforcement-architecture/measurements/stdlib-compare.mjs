import fs from 'fs';
const S=process.argv[2];
const std=JSON.parse(fs.readFileSync(S+'/std.json')); const bp=JSON.parse(fs.readFileSync(S+'/bp.json'));
const bpm=new Map(bp.map(m=>[m.pkg+'/'+m.r,m]));
const L1=new Set('dasum daxpy dcopy ddot dnrm2 drot drotm dscal dsdot dswap idamax dzasum dznrm2 zaxpy zcopy zdotc zdotu zdrot zdscal zscal zswap izamax'.split(' '));
const row=[];
let stats={both:0,ndSigEq:0,strSigEq:0,chkEq:0,stdOnly:0};
for(const s of std){ const k=s.pkg+'/'+s.r; const b=bpm.get(k);
  const sc=(x)=>x?x.checks.map(c=>c.replace(/:.*/,'')).sort().join(','):'-';
  if(!b){stats.stdOnly++; continue;}
  stats.both++;
  const ndEq=JSON.stringify(s.strided?.params)===JSON.stringify(b.strided?.params);
  const stEq=JSON.stringify(s.wrapper?.params)===JSON.stringify(b.wrapper?.params);
  const ckS=(s.strided?.checks||[]).join(' '), ckB=(b.strided?.checks||[]).join(' ');
  const ckSS=(s.wrapper?.checks||[]).join(' '), ckBS=(b.wrapper?.checks||[]).join(' ');
  if(ndEq)stats.ndSigEq++; if(stEq)stats.strSigEq++; if(ckS===ckB&&ckSS===ckBS)stats.chkEq++;
  row.push({k,ndEq,stEq,ndChk:ckS===ckB,stChk:ckSS===ckBS,s,b});
}
console.log(stats);
console.log('\n## strided signature mismatches');
row.filter(x=>!x.ndEq).forEach(x=>console.log(x.k,'\n  std:',x.s.strided?.params.join(','),'\n  bp :',x.b.strided?.params.join(',')));
console.log('\n## strided signature mismatches');
row.filter(x=>!x.stEq).forEach(x=>console.log(x.k,'\n  std:',x.s.wrapper?.params.join(','),'\n  bp :',x.b.wrapper?.params.join(',')));
console.log('\n## strided check mismatches');
row.filter(x=>!x.ndChk).forEach(x=>console.log(x.k,'\n  std:',x.s.strided?.checks.join(' '),'| quick',x.s.strided?.quick,'\n  bp :',x.b.strided?.checks.join(' '),'| quick',x.b.strided?.quick));
console.log('\n## strided check mismatches');
row.filter(x=>!x.stChk).forEach(x=>console.log(x.k,'\n  std:',x.s.wrapper?.checks.join(' '),'\n  bp :',x.b.wrapper?.checks.join(' ')));
console.log('\n## stdlib validators used'); const v={}; std.forEach(m=>['wrapper','strided'].forEach(f=>(m[f]?.vals||[]).forEach(x=>v[x]=(v[x]||0)+1))); console.log(v);
console.log('\n## stdlib: L1 BLAS strided checks'); std.filter(m=>L1.has(m.r)).forEach(m=>console.log(' ',m.r,'nd:',m.strided?.checks.join(' ')||'(none)','| str:',m.wrapper?.checks.join(' ')||'(none)'));
console.log('\n## stdlib: quick return location'); let q={strided:0,wrapper:0,base:0}; std.forEach(m=>['strided','wrapper','base'].forEach(f=>{if(m[f]?.quick)q[f]++})); console.log(q);
